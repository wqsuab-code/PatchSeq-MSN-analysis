def load():
    feat = pd.read_csv(FEATURE_FILE)
    assign = pd.read_csv(ASSIGN_FILE)
    assign["HC_GC_consensus"] = assign.HC_GC_consensus.astype(str).str.lower().eq("true")
    df = feat.merge(assign, on="MSN_unique_ID", validate="one_to_one")
    df = df[df.HC_GC_consensus].reset_index(drop=True)
    features = [c for c in feat.columns if c != "MSN_unique_ID"]
    oof = pd.read_csv(OOF_FILE)
    df = df.merge(oof, on="MSN_unique_ID", validate="one_to_one")
    assert len(df) == 450 and len(features) == 18
    return df, features


