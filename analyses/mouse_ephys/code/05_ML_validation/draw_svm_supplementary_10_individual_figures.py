def repeated_scan(X, y, c_values, repeats=10):
    cv = RepeatedStratifiedKFold(n_splits=5, n_repeats=repeats, random_state=SEED)
    rows = []
    splits = list(cv.split(X, y))
    for c in c_values:
        for k, (tr, te) in enumerate(splits, 1):
            m = model(c).fit(X[tr], y[tr]); p = m.predict(X[te])
            rows.append({"C": c, "Fold": k, "Accuracy": accuracy_score(y[te], p),
                         "Balanced_accuracy": balanced_accuracy_score(y[te], p),
                         "Macro_F1": f1_score(y[te], p, average="macro"),
                         "Kappa": cohen_kappa_score(y[te], p)})
    return pd.DataFrame(rows)


