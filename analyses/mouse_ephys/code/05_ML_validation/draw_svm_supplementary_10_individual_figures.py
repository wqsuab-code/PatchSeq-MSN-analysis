def permutation(X,y,n_perm=999):
    cv=StratifiedKFold(5,shuffle=True,random_state=SEED); splits=list(cv.split(X,y))
    obs=[]
    for tr,te in splits:
        p=model(.1).fit(X[tr],y[tr]).predict(X[te]); obs.append(balanced_accuracy_score(y[te],p))
    observed=np.mean(obs); rng=np.random.default_rng(SEED); null=[]
    for _ in range(n_perm):
        yp=rng.permutation(y); scores=[]
        for tr,te in splits:
            p=model(.1).fit(X[tr],yp[tr]).predict(X[te]); scores.append(balanced_accuracy_score(yp[te],p))
        null.append(np.mean(scores))
    null=np.array(null); pval=(1+np.sum(null>=observed))/(n_perm+1)
    pd.DataFrame({"Permutation":np.arange(1,n_perm+1),"Null_balanced_accuracy":null}).to_csv(OUT/"09_permutation_null.csv",index=False)
    (OUT/"09_permutation_summary.json").write_text(json.dumps({"Observed_mean_fold_balanced_accuracy":observed,"N_permutations":n_perm,"Empirical_P":pval},indent=2))
    fig,ax=plt.subplots(); ax.hist(null,bins=28,color="#BDBDBD",edgecolor="white",lw=.3); ax.axvline(observed,color="#B2182B",lw=1.2,label=f"Observed = {observed:.3f}\nP = {pval:.3g}")
    ax.set_xlabel("Mean 5-fold balanced accuracy"); ax.set_ylabel("Permutations"); ax.set_title("Label-permutation test (fixed C = 0.1)"); ax.legend(frameon=False,fontsize=5); ax.spines[["top","right"]].set_visible(False)
    save(fig,"09_label_permutation_test",3.15,2.3)


def coefficient_heatmap(X,y,features,repeats=10):
    cv=RepeatedStratifiedKFold(n_splits=5,n_repeats=repeats,random_state=SEED); coefs=[]
    for tr,te in cv.split(X,y):
        m=Pipeline([
            ("transform", TranscriptomeLikeTransformer()),
            ("scale", StandardScaler()),
            ("model", OneVsRestClassifier(SVC(kernel="linear", C=.1, class_weight="balanced", random_state=SEED))),
        ]).fit(X[tr],y[tr])
        coefs.append(np.vstack([est.coef_[0] for est in m.named_steps["model"].estimators_]))
    arr=np.stack(coefs); mean=arr.mean(0); sd=arr.std(0,ddof=1)
    labels=[FEATURE_LABELS.get(f,f) for f in features];
    pd.DataFrame(mean,index=CLASSES,columns=labels).to_csv(OUT/"10_linear_SVM_standardized_coefficients_mean.csv")
    pd.DataFrame(sd,index=CLASSES,columns=labels).to_csv(OUT/"10_linear_SVM_standardized_coefficients_sd.csv")
    vmax=np.quantile(np.abs(mean),.98); fig,ax=plt.subplots(); im=ax.imshow(mean,cmap="RdBu_r",vmin=-vmax,vmax=vmax,aspect="auto")
    ax.set_xticks(range(len(labels)),labels,rotation=65,ha="right"); ax.set_yticks(range(5),CLASSES); ax.set_ylabel("One-vs-rest decision function"); ax.set_title("Signed one-vs-rest linear-SVM coefficients\npost hoc surrogate; mean across 50 training folds")
    fig.colorbar(im,ax=ax,label="Signed coefficient",fraction=.025,pad=.02); save(fig,"10_signed_linear_SVM_feature_weights",6.1,2.4)


def main():
    style(); df,features=load(); X=df[features].to_numpy(float); y=df.True_E.to_numpy()
    matrix_figures(df); workflow()
    scan=repeated_scan(X,y,[.01,.03,.1,.3,1,3,10],10); c_scan(scan)
    class_performance(df); roc_pr(df); probability_heatmap(df); error_tsne(df)
    stability(scan[scan.C.eq(.1)].copy()); permutation(X,y,999); coefficient_heatmap(X,y,features,10)
    summary={"N":450,"Support":df.True_E.value_counts().sort_index().to_dict(),"Nested_OOF_accuracy":accuracy_score(df.True_E,df.Predicted_E),"Nested_OOF_balanced_accuracy":balanced_accuracy_score(df.True_E,df.Predicted_E),"Nested_OOF_macro_F1":f1_score(df.True_E,df.Predicted_E,average="macro"),"Selected_C":.1,"Seed":SEED}
    (OUT/"00_analysis_summary.json").write_text(json.dumps(summary,indent=2),encoding="utf-8")
    print(json.dumps(summary,indent=2)); print(OUT)


if __name__ == "__main__":
    main()
