def class_performance(df):
    y, p = df.True_E.to_numpy(), df.Predicted_E.to_numpy(); cm = confusion_matrix(y,p,labels=CLASSES)
    rows=[]
    for i,c in enumerate(CLASSES):
        tp=cm[i,i]; fn=cm[i].sum()-tp; fp=cm[:,i].sum()-tp; tn=cm.sum()-tp-fn-fp
        rows.append({"Class":c,"Precision":tp/(tp+fp),"Recall_sensitivity":tp/(tp+fn),"Specificity":tn/(tn+fp),"F1":f1_score(y==c,p==c),"Support":cm[i].sum()})
    tab=pd.DataFrame(rows); tab.to_csv(OUT/"04_classwise_metrics.csv",index=False)
    fig,ax=plt.subplots(); x=np.arange(5); width=.19
    for k,(metric,color) in enumerate(zip(["Precision","Recall_sensitivity","Specificity","F1"],["#4E79A7","#F28E2B","#59A14F","#B07AA1"])):
        ax.bar(x+(k-1.5)*width,tab[metric],width,label=metric.replace("_sensitivity",""),color=color)
    ax.set_xticks(x,[f"{c}\n(n={n})" for c,n in zip(tab.Class,tab.Support)]); ax.set_ylim(.72,1.01); ax.set_ylabel("Nested OOF score")
    ax.legend(frameon=False,ncol=2,fontsize=5); ax.spines[["top","right"]].set_visible(False); ax.set_title("Class-wise performance")
    save(fig,"04_classwise_performance",3.3,2.35)


def roc_pr(df):
    y=df.True_E.to_numpy(); Y=label_binarize(y,classes=CLASSES); probs=df[[f"P_{c}" for c in CLASSES]].to_numpy()
    roc_rows=[]; pr_rows=[]; fig,axes=plt.subplots(1,2)
    for i,c in enumerate(CLASSES):
        fpr,tpr,_=roc_curve(Y[:,i],probs[:,i]); prec,rec,_=precision_recall_curve(Y[:,i],probs[:,i])
        ra=auc(fpr,tpr); pa=auc(rec[::-1],prec[::-1]); axes[0].plot(fpr,tpr,color=COLORS[c],lw=1,label=f"{c} ({ra:.3f})"); axes[1].plot(rec,prec,color=COLORS[c],lw=1,label=f"{c} ({pa:.3f})")
        roc_rows.append({"Class":c,"ROC_AUC":ra}); pr_rows.append({"Class":c,"PR_AUC":pa})
    fpr,tpr,_=roc_curve(Y.ravel(),probs.ravel()); prec,rec,_=precision_recall_curve(Y.ravel(),probs.ravel())
    micro_roc=auc(fpr,tpr); micro_pr=auc(rec[::-1],prec[::-1]); macro_roc=np.mean([r["ROC_AUC"] for r in roc_rows]); macro_pr=np.mean([r["PR_AUC"] for r in pr_rows])
    axes[0].plot([0,1],[0,1],ls="--",color=".6",lw=.6); axes[0].set(xlabel="False-positive rate",ylabel="True-positive rate",title=f"One-vs-rest ROC\nmicro={micro_roc:.3f}, macro={macro_roc:.3f}")
    axes[1].set(xlabel="Recall",ylabel="Precision",title=f"One-vs-rest precision–recall\nmicro={micro_pr:.3f}, macro={macro_pr:.3f}")
    for ax in axes: ax.set_xlim(0,1); ax.set_ylim(0,1.02); ax.legend(frameon=False,fontsize=4.5); ax.spines[["top","right"]].set_visible(False)
    pd.DataFrame(roc_rows).merge(pd.DataFrame(pr_rows),on="Class").to_csv(OUT/"05_ovr_auc_metrics.csv",index=False)
    save(fig,"05_one_vs_rest_ROC_PR",5.2,2.25)


