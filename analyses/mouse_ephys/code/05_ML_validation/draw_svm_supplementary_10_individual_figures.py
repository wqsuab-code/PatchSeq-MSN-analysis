class TranscriptomeLikeTransformer(BaseEstimator, TransformerMixin):
    def fit(self, X, y=None):
        a = np.asarray(X, float)
        self.minimum_ = np.nanmin(a, axis=0)
        shifted = np.maximum(a - self.minimum_, 0)
        self.column_sum_ = shifted.sum(axis=0)
        self.column_sum_[self.column_sum_ <= 0] = 1
        return self

    def transform(self, X):
        a = np.asarray(X, float)
        shifted = np.maximum(a - self.minimum_, 0)
        return np.log1p(shifted / self.column_sum_ * 10000)


def model(c=0.1, probability=False):
    return Pipeline([
        ("transform", TranscriptomeLikeTransformer()),
        ("scale", StandardScaler()),
        ("model", SVC(kernel="linear", C=c, class_weight="balanced",
                      probability=probability, random_state=SEED)),
    ])


